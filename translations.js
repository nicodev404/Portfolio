const languageToggle = document.getElementById('language-toggle');
const elementsToTranslate = document.querySelectorAll('[data-translate]');

function changeLanguage(lang){

    const elementsToTranslate = document.querySelectorAll('[data-translate]');
    const translationSet = translations[lang];

    
    if(!translationSet) return;
    document.documentElement.lang = lang;

    elementsToTranslate.forEach(element => {
        const key = element.getAttribute('data-translate');
        const translation = translationSet[key];
        
        if(translation){
            if(element.tagName === 'INPUT' && (element.type === 'submit' || element.type === 'button')){
                element.value = translation;
            }
            else if(element.tagName === 'INPUT' || element.tagName === 'TEXTAREA'){
                element.placeholder = translation;
            }
            else{
                element.textContent = translation;
            }
            
        }
    });
    
    document.querySelectorAll("[data-translate-alt]").forEach(img => {
    const key = img.getAttribute("data-translate-alt");

    if (translations[lang]?.[key]) {
        img.alt = translations[lang][key];
    }
    });
    if (window.updateValidationMessages) {
    window.updateValidationMessages(lang);
    }

    localStorage.setItem('preferredLang', lang);
}

window.addEventListener('DOMContentLoaded', () => {
    const languageToggle = document.getElementById('language-toggle');

    const savedLang = localStorage.getItem('preferredLang') || 'en';
    
    languageToggle.checked = (savedLang === 'en');
    
    changeLanguage(savedLang);

    languageToggle.addEventListener('change', () => {
        const newLang = languageToggle.checked ? 'en' : 'es';
        changeLanguage(newLang);
    });
});